#pragma once

#include <string_view>
#include "source.hpp"

// operator table entry, defined in operators.hpp
struct OpInfo;

enum class TokenKind {
    Error,   // malformed input
    Eof,     // end of file
    Identifier,     // user names: foo, main, my_var, and also if
    TypeName,       // any built-in type spelling: i64, i8uw, f32, f16e8m7n, char, rune, bool, ...
    IntLiteral,     // 42, 0b1010, 0o17, 0xFF (text kept raw)
    FloatLiteral,   // 3.14, 0x1.8
    StringLiteral,  // "hello world"
    CharLiteral,    // '\t', '\n', 'a'
    // Declarations
    KwLet, KwType, KwExport, KwImport,
    // Scopes
    KwMatch, KwRepeat, KwChunk,
    // Modes, qualifiers, and handles
    KwUnscoped, KwPeek, KwMut, KwPtr, KwArr,
    // Place intrinsics
    KwTake, KwSwap, KwReplace,
    // Verification
    KwWit, KwAssert, KwOld,
    // Literals
    KwTrue, KwFalse,
    // Macro keywords
    KwMacro, KwMoya,
    // Flow  (<-  ->  -|)
    LArrow, RArrow, Yield,
    // Pipes  (|>  <|)
    PipeFwd, PipeBack,
    // Arithmetic  (+  -  *  /  %)   -- unary minus reuses Minus
    Plus, Minus, Star, Slash, Percent,
    // Bitwise  (&  |  ^  ~  <<  >>)
    Amp, Pipe, Caret, Tilde, Shl, Shr,
    // Logical  (&&  ||  ^^  !)
    AmpAmp, PipePipe, CaretCaret, Bang,
    // Comparison  (<  <=  >  >=)
    Lt, Le, Gt, Ge,
    // Equality  (=  !=  shallow, ==  !==  deep)
    Eq, Ne, EqEq, NeEq,
    // Generated by the operator table: every X<- and every extra operator
    CompoundAssign, ExtraOp,
    // Macro tokens
    At, Buck,
    LParen, RParen,         // ( )
    LBracket, RBracket,     // [ ]
    LBrace, RBrace,         // { }
    Comma, Semi, Dot,       // , ; .
    Colon, ColonColon,      // : ::
    Ellipsis, Underscore,   // ... _
};

// tokens hold their kind, the actual text, their location, and their operator table entry if they're an operator
struct Token {
    TokenKind kind;
    std::string_view text;
    SourceLoc loc;
    const OpInfo* op;
    Token(TokenKind k, std::string_view t, SourceLoc l, const OpInfo* o = nullptr) : kind(k), text(t), loc(l), op(o) {}
};
